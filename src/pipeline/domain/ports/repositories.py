from typing import Any, Protocol


class SettingsRepository(Protocol):
    def get(self) -> Any: ...
    def update(self, default_cli_provider: str, active_project_provider: str, provider_settings: dict[str, Any]) -> Any: ...


class AgentRepository(Protocol):
    def get_by_id(self, agent_id: int) -> Any | None: ...
    def get_by_name(self, name: str) -> Any | None: ...
    def list_all(self, active_only: bool = False) -> list[Any]: ...
    def create(self, name: str, cli_provider: str, model_id: str, prompt_markdown: str, active: bool = True) -> Any: ...
    def update(self, agent_id: int, **kwargs: Any) -> Any: ...
    def delete(self, agent_id: int) -> bool: ...


class ProjectRepository(Protocol):
    def get_by_id(self, project_id: int) -> Any | None: ...
    def get_by_key(self, project_key: str) -> Any | None: ...
    def list_all(self, active_only: bool = False) -> list[Any]: ...
    def create(self, project_key: str, name: str, local_path: str, active: bool = True) -> Any: ...
    def update(self, project_id: int, **kwargs: Any) -> Any: ...
    def delete(self, project_id: int) -> bool: ...


class FlowColumnRepository(Protocol):
    def get_by_id(self, column_id: int) -> Any | None: ...
    def get_by_identifier(self, identifier: str) -> Any | None: ...
    def get_by_column_name(self, column_name: str) -> Any | None: ...
    def list_all(self, active_only: bool = False) -> list[Any]: ...
    def create(
        self,
        identifier: str,
        column_name: str,
        agent_id: int | None = None,
        next_column_name: str | None = None,
        order_index: int = 0,
        active: bool = True,
    ) -> Any: ...
    def update(self, column_id: int, **kwargs: Any) -> Any: ...
    def delete(self, column_id: int) -> bool: ...


class JobRepository(Protocol):
    def get_by_id(self, job_id: int) -> Any | None: ...
    def list_all(
        self,
        project_id: int | None = None,
        card_id: int | None = None,
        state: str | None = None,
        limit: int = 100,
    ) -> list[Any]: ...
    def get_active_job_for_card(self, card_id: int, flow_column_id: int) -> Any | None: ...
    def create(
        self,
        project_id: int,
        card_id: int,
        flow_column_id: int,
        agent_id: int | None,
        cli_provider_snapshot: str | None,
        model_id_snapshot: str | None,
        target_column_snapshot: str | None,
        state: str = "pending",
        iteration: int = 1,
    ) -> Any: ...
    def update(self, job_id: int, **kwargs: Any) -> Any: ...
    def delete(self, job_id: int) -> bool: ...


class CardRepository(Protocol):
    def get_by_id(self, card_id: int) -> Any | None: ...
    def get_by_remote_id(self, project_id: int, remote_id: str) -> Any | None: ...
    def list_by_project(self, project_id: int, include_removed: bool = False) -> list[Any]: ...
    def create(
        self,
        project_id: int,
        remote_id: str,
        title: str,
        body: str,
        column_name: str,
        url: str | None = None,
        issue_number: int | None = None,
        content_hash: str | None = None,
    ) -> Any: ...
    def update(self, card_id: int, **kwargs: Any) -> Any: ...


class CardEventRepository(Protocol):
    def list_by_card(self, card_id: int) -> list[Any]: ...
    def list_recent(self, limit: int = 50) -> list[Any]: ...
    def create(
        self,
        card_id: int,
        event_type: str,
        from_column: str | None = None,
        to_column: str | None = None,
        is_rework: bool = False,
    ) -> Any: ...


class CliModelRepository(Protocol):
    def list_by_provider(self, cli_provider: str, available_only: bool = True) -> list[Any]: ...
    def list_all(self, available_only: bool = False) -> list[Any]: ...
    def upsert_models(self, cli_provider: str, models: list[Any]) -> None: ...


class PipelineRunRepository(Protocol):
    def get_by_id(self, run_id: int) -> Any | None: ...
    def list_recent(self, limit: int = 50) -> list[Any]: ...
    def create(
        self,
        trigger: str,
        project_provider_used: str,
        project_id: int | None = None,
        cli_provider_used: str | None = None,
    ) -> Any: ...
    def update(self, run_id: int, **kwargs: Any) -> Any: ...
